"""Research beside the MarketView (M6-09; D52, D53; design principle E-01).

Advisory evidence only: shown, never used by sizing, risk or orders. Status is
always written in words (VALID / EXPIRED / No research), never conveyed by colour
alone. Every model-produced string is escaped. Missing research is shown as
missing, never as a default rating.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from html import escape

from investment_engine.market.availability import check_utc
from investment_engine.research.contracts import ResearchContext, ResearchRecord, RunOutcome

ADVISORY = "ADVISORY research: not used by sizing, risk or orders"
NOT_REPRODUCIBLE = "Reconstructable from its stored record, not reproducible: a new run can answer differently"


@dataclass(frozen=True)
class ResearchEvidence:
    context: ResearchContext | None
    record: ResearchRecord | None  # the context's run, or the latest failed run when there is no context
    at: datetime  # when the panel is assessed (VALID / EXPIRED)

    def __post_init__(self) -> None:
        check_utc(self.at, "at")
        if self.record is not None and self.record.finished_at > self.at:
            raise ValueError("research evidence cannot come from a run that finished after its assessment time")
        if self.context is None:
            return
        if self.record is None or self.record.run_id != self.context.run_id:
            raise ValueError("a shown research context needs its own run record")
        if self.record.outcome is not RunOutcome.SUCCEEDED or self.context.generated_at != self.record.finished_at:
            raise ValueError("a shown research context must come from its succeeded run, generated when it finished")
        if self.context.generated_at > self.at:
            raise ValueError("research cannot be shown before it was generated")


def _lines(e: ResearchEvidence) -> list[str]:
    lines = [ADVISORY]
    ctx, rec = e.context, e.record
    if ctx is None:
        lines.append("No research for this instrument (none requested, none succeeded, or none generated yet).")
        if rec is not None and rec.failure:
            lines.append(f"Latest run {rec.run_id} did not produce research: {rec.failure}")
        return lines
    status = ctx.status(e.at)
    lines.append(f"Status: {status}" + (f" until {ctx.valid_until.isoformat()}" if status == "VALID"
                                        else f" since {ctx.valid_until.isoformat()}"))
    lines.append(f"Rating: {ctx.rating.value} (source {ctx.source.value})")
    lines.append(f"Trader action: {ctx.trader_action.value if ctx.trader_action else 'unavailable'}")
    levels = ctx.suggested_levels
    lines.append(f"{levels.label}: entry {levels.entry if levels.entry is not None else 'none'}, "
                 f"stop {levels.stop if levels.stop is not None else 'none'}")
    lines.append(f"Generated {ctx.generated_at.isoformat()}; horizon {ctx.horizon_sessions} sessions")
    s = rec.settings
    lines.append(f"Models: {s.provider} {s.quick_model} / {s.deep_model}; upstream {rec.upstream_version}; "
                 f"code {rec.code_version}; run {rec.run_id}")
    lines.extend(f"Warning: {w}" for w in ctx.warnings)
    lines.append(NOT_REPRODUCIBLE)
    return lines


def panel_text(evidence: ResearchEvidence) -> str:
    return "\n".join(_lines(evidence))


def panel_html(evidence: ResearchEvidence) -> str:
    items = "".join(f"<li>{escape(line, quote=True)}</li>" for line in _lines(evidence)[1:])
    return (f'<section class="panel research"><h2>Research (advisory)</h2>'
            f'<p><strong>{escape(ADVISORY)}</strong></p><ul>{items}</ul></section>')


def view_with_research_text(view, evidence: ResearchEvidence) -> str:
    """The latest MarketView and, beside it, the latest research: two separate, labelled blocks."""
    if view is None:
        head = ["Latest view: none stored for this instrument."]
    else:
        head = [f"Latest view ({view.instrument_id}) at {view.generated_at.isoformat()}: {view.direction.value}, "
                f"strength {view.strength:.2f} (a scale, not a probability), valid until {view.valid_until.isoformat()}"]
        if view.abstain_reason:
            head.append(f"Abstain reason: {view.abstain_reason}")
    return "\n".join(head + ["", "--- Research ---", panel_text(evidence)])


def latest_evidence(db, instrument_id: str, *, at: datetime) -> ResearchEvidence:
    """Read-only: the newest context generated by `at`, with its record; else the newest failed run's record."""
    from investment_engine.audit.events import AuditStore
    from investment_engine.events.outbox import Outbox
    from investment_engine.oms.order_states import ProcessRole
    from investment_engine.research.store import ResearchStore

    class _Clock:
        def now(self):
            return at

    store = ResearchStore(db, role=ProcessRole.CORE, audit=AuditStore(db),
                          outbox=Outbox(db, writer=ProcessRole.CORE, clock=_Clock()), clock=_Clock())
    context = store.latest_context(instrument_id, at=at)
    if context is not None:
        return ResearchEvidence(context, store.record(context.run_id), at)
    row = db.fetchone("SELECT r.run_id FROM research_records r JOIN research_jobs j USING (job_id) "
                      "WHERE j.instrument_id = :i AND r.finished_at <= :t ORDER BY r.finished_at DESC, r.run_id DESC "
                      "LIMIT 1", {"i": instrument_id, "t": at})
    return ResearchEvidence(None, None if row is None else store.record(row[0]), at)


__all__ = ["ADVISORY", "NOT_REPRODUCIBLE", "ResearchEvidence", "latest_evidence", "panel_html", "panel_text",
           "view_with_research_text"]
